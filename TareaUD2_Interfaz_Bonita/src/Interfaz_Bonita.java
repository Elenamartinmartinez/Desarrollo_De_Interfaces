    private void TxtNombreFocusGained(java.awt.event.FocusEvent evt) {//GEN-FIRST:event_TxtNombreFocusGained
        //Texto por defecto de la caja de texto
        if (TxtNombre.getText().equals("Ingrese su nombre de usuario")) {
            TxtNombre.setText("");
            TxtNombre.setForeground(java.awt.Color.BLACK);
        }
    }//GEN-LAST:event_TxtNombreFocusGained

    private void TxtNombreFocusLost(java.awt.event.FocusEvent evt) {//GEN-FIRST:event_TxtNombreFocusLost
        if (TxtNombre.getText().isEmpty()) {
            TxtNombre.setText("Ingrese su nombre de usuario");
            TxtNombre.setForeground(java.awt.Color.GRAY);
        }
    }//GEN-LAST:event_TxtNombreFocusLost

    private void PwdClaveFocusGained(java.awt.event.FocusEvent evt) {//GEN-FIRST:event_PwdClaveFocusGained
        if (String.valueOf(PwdClave.getPassword()).equals("Ingrese su contraseña")) {
            PwdClave.setText("");
            PwdClave.setForeground(java.awt.Color.BLACK);
            PwdClave.setEchoChar('*');
        }
    }//GEN-LAST:event_PwdClaveFocusGained

    private void PwdClaveFocusLost(java.awt.event.FocusEvent evt) {//GEN-FIRST:event_PwdClaveFocusLost
        if (String.valueOf(PwdClave.getPassword()).isEmpty()) {
            PwdClave.setEchoChar((char)0);
            PwdClave.setText("Ingrese su contraseña");
            PwdClave.setForeground(java.awt.Color.GRAY);
        }
    }//GEN-LAST:event_PwdClaveFocusLost

